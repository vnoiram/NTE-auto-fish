def set_language(language: str) -> str:
    """Set the active GUI language and return the normalized code."""
    global _current_language
    _current_language = language if language in SUPPORTED_LANGUAGES else "en"
    return _current_language


def get_language() -> str:
    return _current_language


def tr(message: str, **values) -> str:
    """Translate an English source message and optionally format placeholders."""
    translated = _JA.get(message, message) if _current_language == "ja" else message
    return translated.format(**values) if values else translated


def language_label(language: str) -> str:
    return LANGUAGE_LABELS.get(language, LANGUAGE_LABELS["en"])


def language_from_label(label: str) -> str:
    for code, display in LANGUAGE_LABELS.items():
        if display == label:
            return code
    return "en"
